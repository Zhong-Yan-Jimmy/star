/* ══ 从光谱型推出来的一切 ══

   光谱型是这份数据里信息密度最高的一个字段：它同时决定了这颗星的颜色、
   类别，以及它大致处在演化的哪个阶段。所以这三件事全从它推，不另存。 */

const STAR_CLASS_ZH = {
  O: '蓝色主序星', B: '蓝白色主序星', A: '白色主序星', F: '黄白色主序星',
  G: '黄矮星', K: '橙矮星', M: '红矮星'
};

/* 光谱型开头的 d / sd 是矮星与亚矮星的标记，颜色由后面的温度级决定，
   所以先剥掉。'sdM4' → 'M4'，而 'DA2' 的 D 是大写、不是前缀，要留着。 */
function starClassOf(spec) {
  return (spec || '').replace(/^[a-z]+/, '');
}

function starType(spec) {
  const s = starClassOf(spec);
  if (!s) return '光谱型未知';
  const cls = s[0];
  if (cls === 'D') return '白矮星';                                  // DA / DB / DC / DG…
  if (cls === 'L' || cls === 'T' || cls === 'Y') return '褐矮星';     // 温度低到连氢都没点燃
  // 罗马数字要长的先判：'K2IIIp' 里同时含有 II 和 III
  if (/III/.test(s)) return '巨星';
  if (/II/.test(s)) return '亮巨星';
  if (/IV/.test(s)) return '亚巨星';
  return STAR_CLASS_ZH[cls] || '恒星';
}

function starColor(spec) {
  const s = starClassOf(spec);
  if (!s) return STAR_UNKNOWN_COLOR;
  const cls = s[0];
  if (cls === 'D') return STAR_WD_COLOR;
  return STAR_BD_COLOR[cls] || STAR_SPEC_COLOR[cls] || STAR_UNKNOWN_COLOR;
}

/* 肉眼极限约 6.5 等，这条线两侧的差别是「看得见」和「看不见」——
   比精确到小数点后两位的星等本身更值得告诉人。 */
function magText(mag) {
  if (mag === null || mag === undefined || !isFinite(mag)) return '肉眼不可见';
  return mag.toFixed(2) + (mag > 6.5 ? '（肉眼不可见）' : '');
}

function starFacts(spec, mag, dist, planets, mass, radius) {
  return [
    ['距离', dist.toFixed(2) + ' 光年'],
    ['光谱型', spec || '未知'],
    ['视星等', magText(mag)],
    ['质量', mass === null || mass === undefined ? '未知' : mass + ' M☉'],
    ['半径', radius === null || radius === undefined ? '未知' : radius + ' R☉'],
    ['已知行星', planets === null || planets === undefined ? '未知'
              : planets === 0 ? '无' : planets + ' 颗']
  ];
}

/* 一百多颗星里的绝大多数确实没什么可说的，模板就照实写它是什么、
   在多远、看不看得见，不硬凑故事。 */
function starTemplateDesc(zh, type, spec, dist, mag) {
  const v = (mag === null || mag === undefined || !isFinite(mag))
    ? '它的可见光弱到几乎测不到，只能在红外波段上观测'
    : mag > 6.5
      ? '它太暗，肉眼看不见，得靠望远镜才能找到'
      : '在足够暗的夜空里，它肉眼可见';
  return zh + '是一颗' + type + (spec ? '，光谱型 ' + spec : '') +
         '，距离我们 ' + dist.toFixed(2) + ' 光年。' + v + '。';
}

/* 把一行元组展开成与行星完全同构的对象 —— openInfo() 一行都不用改。
   radius 取的是这颗星在场景里的显示尺寸（星等桶的 size），不是它的真实
   半径：focusDistanceOf() 拿它算聚焦距离，而真实的太阳半径 0.00465 AU
   会让镜头一路贴到星面上。 */
function expandStar(row) {
  const [id, zh, en, ra, dec, dist, spec, mag, planets, mass, radius] = row;
  const note = STAR_NOTES[id] || {};
  const bucket = STAR_MAG_BUCKETS.find(b =>
    (mag === null || mag === undefined || !isFinite(mag) ? Infinity : mag) < b.max
  ) || STAR_MAG_BUCKETS[STAR_MAG_BUCKETS.length - 1];
  const type = starType(spec);
  return {
    id, name: zh, en, type,
    /* badge 在行星那边是「一句话卖点」（金星：太阳系最热行星），恒星里
       只有 38 颗写得出这种话，剩下的退回光谱型。不退回 type ——
       badge 下面那行的「en · type」已经写着橙矮星了，两处都写就是复读。
       光谱型反而正好补位：一个给专业读者，一个给普通读者。 */
    badge: note.badge || spec || type,
    ra, dec, dist, spec, mag,
    radius: bucket.size,
    color: starColor(spec),
    facts: starFacts(spec, mag, dist, planets, mass, radius),
    desc: note.desc || starTemplateDesc(zh, type, spec, dist, mag),
    highlights: note.highlights || []
  };
}

/* 按距离升序 —— 顺序是契约的一部分：左栏列表的点击绑定靠下标，
   而排序必须发生在产出列表之前，不能留到渲染的时候再做。 */
const NEARBY_STARS = NEARBY_STARS_RAW
  .map(expandStar)
  .sort((a, b) => a.dist - b.dist);
