/* B−V 色指数 → 光谱型 → 颜色，走的是 data.js 那套 STAR_SPEC_COLOR，
   与内层同一组色。分档界是天文上的惯用值。 */
const SKY_BV_BANDS = [
  ['B', -0.02], ['A', 0.30], ['F', 0.58], ['G', 0.81], ['K', 1.40], ['M', Infinity]
];

function skyColorFromBV(bv) {
  /* 实测这份数据 5044 颗的 bv 一个不缺，但兜底还是要的 ——
     拿不到时给 0.65（太阳的 B−V，落在 G 档近白），
     总之不能是 NaN，NaN 灌进顶点色会让那颗星整颗变成黑的。 */
  const v = (bv === null || bv === undefined || !isFinite(bv)) ? 0.65 : bv;
  const band = SKY_BV_BANDS.find(b => v < b[1]);
  return STAR_SPEC_COLOR[band ? band[0] : 'M'];
}
